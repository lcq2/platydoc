"""Package a classic-script, direct-file browser proof without fetch or a server."""
import argparse
import base64
import hashlib
import json
from pathlib import Path
import shutil
import sys
import tempfile

ROOT = Path(__file__).resolve().parent
sys.dont_write_bytecode = True
sys.path.insert(0, str(ROOT / "tests"))
from fixtures import cases, validate  # noqa: E402


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--wasm", type=Path, required=True, help="Emscripten factory .js")
    parser.add_argument("--native-report", type=Path, required=True)
    parser.add_argument("--notices", type=Path, required=True, help="LLVM/SDK notice directory from build.py")
    parser.add_argument("--provenance", type=Path, required=True, help="build.py toolchain provenance JSON")
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    project = ROOT.parents[2]
    output = args.output.resolve()
    if any(output.is_relative_to(project / forbidden) for forbidden in ("docs-ai", "xnu")):
        raise SystemExit("proof output must be outside docs-ai/ and xnu/")
    native = json.loads(args.native_report.read_text())
    inputs = cases()
    if native["cases"] != [name for name, _ in inputs]:
        raise SystemExit("native report is stale for the fixture matrix")
    for (name, _), result in zip(inputs, native["results"], strict=True):
        validate(name, result)
    wasm_path = args.wasm.with_suffix(".wasm")
    binary = wasm_path.read_bytes()
    if native.get("wasm_sha256") != hashlib.sha256(binary).hexdigest() or native.get("wasm_parity") != "passed":
        raise SystemExit("a passing native/Wasm comparison for this exact artifact is required")
    if native.get("wasm_factory_sha256") != hashlib.sha256(args.wasm.read_bytes()).hexdigest():
        raise SystemExit("native comparison used a different Emscripten factory")
    provenance = json.loads(args.provenance.read_text())
    expected_artifacts = {
        "build-native/bin/layout-engine": native["native_sha256"],
        "build-wasm/bin/layout-engine.js": native["wasm_factory_sha256"],
        "build-wasm/bin/layout-engine.wasm": native["wasm_sha256"],
    }
    for name, digest in expected_artifacts.items():
        if provenance.get("artifacts", {}).get(name, {}).get("sha256") != digest:
            raise SystemExit(f"build provenance differs from compared artifact: {name}")
    if provenance.get("pins", {}).get("llvm", {}).get("revision") != native["results"][0]["compiler"]["revision"]:
        raise SystemExit("build provenance compiler differs from comparison")
    required_notices = {"LLVM-LICENSE.txt", "Clang-LICENSE.txt", "Emscripten-LICENSE.txt", "emsdk-LICENSE.txt"}
    if not required_notices.issubset(provenance.get("notices", {})):
        raise SystemExit("build provenance lacks required upstream notices")
    for name, digest in provenance["notices"].items():
        notice = args.notices / name
        if not notice.is_file() or digest != hashlib.sha256(notice.read_bytes()).hexdigest():
            raise SystemExit(f"missing or changed upstream notice: {name}")
    if args.output.exists() and any(args.output.iterdir()):
        if not (args.output / ".layout-proof").is_file():
            raise SystemExit("refusing to replace nonempty, unmarked proof directory")
    # Build and validate the complete package before replacing the last proof.
    final_output = args.output
    final_output.parent.mkdir(parents=True, exist_ok=True)
    temporary = tempfile.TemporaryDirectory(prefix=".layout-proof-stage-", dir=final_output.parent)
    args.output = Path(temporary.name) / "proof"
    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / ".layout-proof").write_text("Generated by Platydoc layout package_proof.py\n")
    shutil.copyfile(args.wasm, args.output / "layout-engine.js")
    shutil.copyfile(ROOT / "browser/proof.js", args.output / "proof.js")
    shutil.copytree(args.notices, args.output / "licenses", dirs_exist_ok=True)
    shutil.copyfile(project / "LICENSE", args.output / "licenses/Platydoc-GPL-2.0-only.txt")
    shutil.copyfile(args.provenance, args.output / "toolchain-provenance.json")
    # Decode chunks directly into one Wasm allocation. Avoid creating one huge
    # base64 decoded JS string in addition to the final byte array.
    chunks = [base64.b64encode(binary[i:i + 49152]).decode("ascii") for i in range(0, len(binary), 49152)]
    payload = (
        "// Third-party compiler bytes: see licenses/ and manifest.json.\n"
        "function decodeLayoutWasm() {\nconst chunks = " + json.dumps(chunks) + ";\n"
        f"const bytes = new Uint8Array({len(binary)});\nlet offset = 0;\n"
        "for (const chunk of chunks) { const raw = atob(chunk);\n"
        "for (let i = 0; i < raw.length; ++i) bytes[offset++] = raw.charCodeAt(i); }\n"
        "return bytes;\n}\n"
        "window.layoutCases = " + json.dumps([{"name": n, "request": r} for n, r in inputs]) + ";\n"
        "window.layoutExpected = " + json.dumps(native["results"]) + ";\n"
    )
    (args.output / "payload.js").write_text(payload)
    (args.output / "index.html").write_text('''<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>Platydoc layout engine proof</title>
<meta name="viewport" content="width=device-width,initial-scale=1">
<script>window.layoutProofStart = performance.now();</script>
<style>body{font:16px system-ui;max-width:75ch;margin:3em auto;padding:0 1em}pre{white-space:pre-wrap}li{margin:.4em 0}</style>
</head><body><h1>Offline Clang layout engine proof</h1>
<p>This milestone-one prototype analyzes synthetic C records for ARM64 Darwin. Open this file directly. All compiler bytes and inputs are local.</p>
<p id="status" role="status">Loading compiler…</p><ol id="results"></ol>
<h2>Measurements</h2><p>Linear memory is the Wasm buffer capacity, not live allocation or browser process memory. Parse times include JSON serialization and result decoding.</p>
<pre id="metrics"></pre><pre id="stderr"></pre>
<p>Platydoc software: <a href="licenses/Platydoc-GPL-2.0-only.txt">GPL-2.0-only</a>. Compiler and runtime retain upstream terms in <a href="licenses/LLVM-LICENSE.txt">LLVM license</a> and the other bundled notices. See <a href="manifest.json">artifact manifest</a>.</p>
<script src="layout-engine.js"></script><script src="payload.js"></script><script src="proof.js"></script>
</body></html>
''')
    manifest = {
        "kind": "milestone-1-synthetic-offline-proof",
        "compiler": native["results"][0]["compiler"],
        "wasm_bytes": len(binary),
        "warning": "No XNU support or handbook integration is claimed.",
        "files": {},
    }
    for path in sorted(args.output.rglob("*")):
        if path.is_file() and path.name != "manifest.json":
            data = path.read_bytes()
            manifest["files"][path.relative_to(args.output).as_posix()] = {
                "bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()}
    manifest["total_bytes"] = sum(entry["bytes"] for entry in manifest["files"].values())
    (args.output / "manifest.json").write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")
    previous = Path(temporary.name) / "previous"
    if final_output.exists():
        final_output.rename(previous)
    try:
        args.output.rename(final_output)
    except BaseException:
        if previous.exists():
            previous.rename(final_output)
        raise
    temporary.cleanup()
    print(f"Offline proof: {final_output / 'index.html'} ({manifest['total_bytes']:,} bytes excluding manifest)")


if __name__ == "__main__":
    main()
