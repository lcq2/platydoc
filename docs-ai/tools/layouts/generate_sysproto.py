"""Generate sys/sysproto.h using XNU's unmodified syscall generator.

Implements MakeInc.rule's unifdef step and bsd/sys/Makefile's `proto` rule.
Only installed host tools are used. Source stays read-only; no tools are fetched.
An empty seed list is explicit, not a claim about a shipping kernel build.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from paths import PROJECT_ROOT, SOURCE_ROOT, DOCS, require_source

MARKER = '.layout-generated-sysproto'
INPUTS = ('bsd/kern/syscalls.master', 'bsd/kern/makesyscalls.sh',
          'makedefs/MakeInc.rule', 'bsd/sys/Makefile')


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def validate_manifest(manifest, source_inputs, generator_sha256):
    """Bind generated bytes to the original recipe; usable offline without host tools."""
    if (manifest.get('contract'), manifest.get('version')) != ('platydoc.generated-sysproto', 1):
        raise ValueError('Unsupported syscall header generation provenance')
    if (manifest.get('generator_sha256') != generator_sha256 or
            set(manifest.get('source_inputs', {})) != set(INPUTS) or
            any(source_inputs.get(name) != digest for name, digest in manifest['source_inputs'].items()) or
            manifest.get('seed_defines') != [] or
            set(manifest.get('files', {})) != {'bsd.syscalls.master', 'sys/sysproto.h'} or
            manifest.get('recipe') != ['makedefs/MakeInc.rule#L553-L560', 'bsd/sys/Makefile#L340-L343']):
        raise ValueError('Syscall header recipe/source/seed identity changed')
    for digest in manifest['files'].values():
        if not isinstance(digest, str) or not re.fullmatch('[0-9a-f]{64}', digest):
            raise ValueError('Invalid generated syscall file identity')


def load(spec, source_inputs=None):
    selected = spec.get('generated_syscalls')
    if selected is None:
        return None, None
    if selected != {'directory': '.docs-cache/layouts/generated-syscalls',
                    'includes': ['kern/kern_credential.c'], 'seed_defines': []}:
        raise ValueError('Unsupported generated syscall header context')
    root = PROJECT_ROOT / selected['directory']
    if any(path.is_symlink() for path in (root, *root.parents)):
        raise ValueError('Generated syscall input cannot traverse symlinks')
    manifest = json.loads((root / 'generation.json').read_bytes())
    if source_inputs is None:
        source_inputs = {name: sha(SOURCE_ROOT / name) for name in INPUTS}
    validate_manifest(manifest, source_inputs, sha(Path(__file__)))
    for name, digest in manifest['files'].items():
        path = root / name
        if any(part.is_symlink() for part in (path, *path.parents)) or not path.is_file() or sha(path) != digest:
            raise ValueError('Generated syscall header changed: ' + name)
    return root, manifest


def generate(output, defines=(), undefines=()):
    require_source()
    output = Path(output).absolute()
    for ancestor in (output, *output.parents):
        if ancestor.is_symlink(): raise ValueError('Generated header output cannot traverse symlinks')
    output = output.resolve()
    for protected in (SOURCE_ROOT, DOCS, PROJECT_ROOT / '.git'):
        if output == protected or output in protected.parents or protected in output.parents:
            raise ValueError('Generated headers must remain outside source/documentation trees')
    if output.exists() and (not output.is_dir() or any(p.is_symlink() for p in output.rglob('*')) or
                            (any(output.iterdir()) and not (output / MARKER).is_file())):
        raise ValueError('Refusing nonempty unmarked or symlink-containing output')
    seeds, names = [], set()
    for option, entries in (('-D', defines), ('-U', undefines)):
        for entry in entries:
            name = entry.partition('=')[0]
            if not re.fullmatch(r'[A-Za-z_]\w*', name) or name in names or any(c in entry for c in '\0\n\r') or (option == '-U' and '=' in entry):
                raise ValueError('Invalid or repeated SEED_DEFINES input')
            names.add(name); seeds.append(option + entry)
    tools = {}
    for name in ('sh', 'unifdef', 'awk', 'sed', 'touch', 'rm', 'cat'):
        path = shutil.which(name)
        if not path: raise RuntimeError('Missing installed tool: ' + name + '; install it through the system package manager')
        path = Path(path).resolve(); tools[name] = {'path': str(path), 'sha256': sha(path)}
    # The original shell script calls tools by name; use only their installed dirs.
    env = os.environ.copy()
    env.update(LC_ALL='C', PATH=os.pathsep.join(dict.fromkeys(str(Path(t['path']).parent) for t in tools.values())))
    inputs = {name: sha(SOURCE_ROOT / name) for name in INPUTS}
    helper_sha = sha(Path(__file__))
    output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='.sysproto-stage-', dir=output.parent) as temporary:
        stage = Path(temporary) / 'headers'; (stage / 'sys').mkdir(parents=True)
        command = [tools['unifdef']['path'], *seeds, str(SOURCE_ROOT / 'bsd/kern/syscalls.master')]
        process = subprocess.run(command, env=env, capture_output=True, timeout=30)
        if process.returncode not in (0, 1): raise RuntimeError('unifdef failed: ' + process.stderr.decode(errors='replace'))
        (stage / 'bsd.syscalls.master').write_bytes(process.stdout)
        commands = [{'argv': command, 'cwd': '.', 'stdout': 'bsd.syscalls.master',
                     'exit_code': process.returncode, 'stderr': process.stderr.decode(errors='replace')}]
        # Relative input keeps the generated source comment identical at every output location.
        command = [tools['sh']['path'], str(SOURCE_ROOT / 'bsd/kern/makesyscalls.sh'), '../bsd.syscalls.master', 'proto']
        process = subprocess.run(command, cwd=stage / 'sys', env=env, capture_output=True, timeout=30)
        if process.returncode: raise RuntimeError('makesyscalls.sh failed: ' + process.stderr.decode(errors='replace'))
        commands.append({'argv': command, 'cwd': 'sys', 'exit_code': process.returncode,
                         'stderr': process.stderr.decode(errors='replace')})
        generated = {name: sha(stage / name) for name in ('bsd.syscalls.master', 'sys/sysproto.h')}
        if inputs != {name: sha(SOURCE_ROOT / name) for name in INPUTS} or helper_sha != sha(Path(__file__)) or any(sha(Path(t['path'])) != t['sha256'] for t in tools.values()):
            raise RuntimeError('Generation inputs changed while the header was being produced')
        manifest = {'contract': 'platydoc.generated-sysproto', 'version': 1,
                    'recipe': ['makedefs/MakeInc.rule#L553-L560', 'bsd/sys/Makefile#L340-L343'],
                    'source_inputs': inputs, 'generator_sha256': helper_sha, 'seed_defines': seeds,
                    'tools': tools, 'environment': {'LC_ALL': 'C', 'PATH': env['PATH']},
                    'commands': commands, 'files': generated}
        (stage / 'generation.json').write_text(json.dumps(manifest, indent=2, sort_keys=True) + '\n')
        (stage / MARKER).write_text('Platydoc generated XNU syscall prototype header\n')
        previous = Path(temporary) / 'previous'
        if output.exists(): output.rename(previous)
        try: stage.rename(output)
        except BaseException:
            if previous.exists(): previous.rename(output)
            raise
    print('Generated original XNU sysproto:', output / 'sys/sysproto.h')
    return manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=PROJECT_ROOT / '.docs-cache/layouts/generated-syscalls')
    parser.add_argument('--define', action='append', default=[], metavar='NAME[=VALUE]', help='Explicit -D entry in SEED_DEFINES')
    parser.add_argument('--undefine', action='append', default=[], metavar='NAME', help='Explicit -U entry in SEED_DEFINES')
    args = parser.parse_args()
    generate(args.output, args.define, args.undefine)


if __name__ == '__main__': main()
